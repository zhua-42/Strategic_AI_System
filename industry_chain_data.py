    """按行业名获取产业链；支持模糊匹配。返回 (chain_list, matched_industry)。"""
    if industry_name is None:
        return [], None
    ind = str(industry_name).strip()
    # 精确
    if ind in INDUSTRY_CHAINS:
        return INDUSTRY_CHAINS[ind], ind
    # 模糊
    for key, chain in INDUSTRY_CHAINS.items():
        if key in ind or ind in key:
            return chain, key
